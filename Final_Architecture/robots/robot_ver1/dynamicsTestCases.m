function cases = dynamicsTestCases(robot)
% DYNAMICSTESTCASES Robot-specific preliminary motion definitions.

% Editable motion settings for the outer-reach line.
tcpSpeed = 0.08;          % m/s
tcpAcceleration = 0.15;  % m/s^2
tcpJerk = 0.40;          % m/s^3
timeStep = 0.05;         % s
spatialStep = 0.01;      % m between Cartesian IK knots

if robot.structure.dof ~= 6
    error('robot_ver1:DynamicsCaseDOF', ...
        'The robot_ver1 dynamics cases require the six-axis model.');
end

base = struct('id',"",'name',"",'description',"",'category',"", ...
    'path',struct(),'startConfiguration',zeros(1,6),'motion',struct(), ...
    'validation',struct(),'enabled',true,'dataStatus',"PRELIMINARY", ...
    'collisionStatus',"NOT_CHECKED",'source',"robot_ver1 test catalog", ...
    'disabledReason',"",'notes',strings(0,1));
cases = repmat(base,2,1);

gravityCase = base;
gravityCase.id = "GRAVITY_HOLD";
gravityCase.name = "Stationary gravity search";
gravityCase.description = ...
    "Finds separate stationary gravity-torque peaks for every joint.";
gravityCase.category = "gravity";
gravityCase.startConfiguration = robot.params.joints.homePosition;
gravityCase.source = "Provisional joint-limit domain";
gravityCase.notes = ...
    "Collision constraints are not yet included in the gravity search.";
cases(1) = gravityCase;

outerLine = base;
outerLine.id = "EXTREME_LONG_LINE";
outerLine.name = "Outer-reach 300 mm horizontal line";
outerLine.description = ...
    "Constant-orientation horizontal line near the current kinematic reach boundary.";
outerLine.category = "preliminary_dynamics";
outerLine.startConfiguration = [ ...
    1.15232822075669  1.61388934112674 -1.62003857311206 ...
    1.17572005402531  1.21938497085853 -1.96835775201378];
outerLine.path = struct( ...
    'type',"line", ...
    'endPosition',[-0.354726451856908; -0.911189552779804; 0.479164055094604], ...
    'orientationMode',"constant");
outerLine.motion = struct( ...
    'profile',"scurve", ...
    'tcpSpeed',tcpSpeed, ...
    'tcpAcceleration',tcpAcceleration, ...
    'tcpJerk',tcpJerk, ...
    'timeStep',timeStep, ...
    'spatialStep',spatialStep);
outerLine.validation = struct( ...
    'maxPositionError_m',2e-3, ...
    'maxOrientationError_rad',5e-3, ...
    'maxJointStepRad',deg2rad(15), ...
    'maxSpatialJointStepRad',deg2rad(15), ...
    'requireSmoothStop',true);
outerLine.dataStatus = "PRELIMINARY";
outerLine.collisionStatus = "NOT_CHECKED";
outerLine.source = "Validated robot_ver1 outer-workspace test motion";
outerLine.notes = [ ...
    "The line is 0.300 m long and remains at constant base-frame Z." ...
    "Its horizontal TCP radius is approximately 0.966 to 0.978 m." ...
    "Self-collision, environment collision, and welding forces are not included."];

cases(2) = outerLine;

end
